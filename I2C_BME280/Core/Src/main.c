  if (status != 0){
	  Error_Handler();
  }

  if (Read_From_BME280() != HAL_OK) {
	  Error_Handler();
  }

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */

  uint32_t now = 0, next_tick = 1000, loop_cnt = 0;

  while (1)
  {
	  now = HAL_GetTick();

	  if (now >= next_tick) {

	  	printf("Tick %lu (loop = %lu)\n\r", now / 1000, loop_cnt);

	  	loop_cnt = 0;
	  	next_tick = now + 1000;

	  }

	  ++loop_cnt;
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
