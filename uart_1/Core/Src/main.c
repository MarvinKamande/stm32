// Send printf to uart2
int _write(int fd, char* ptr, int len) {
  HAL_StatusTypeDef hstatus;

  if (fd == 1 || fd == 2) {
    hstatus = HAL_UART_Transmit(&huart2, (uint8_t *) ptr, len, HAL_MAX_DELAY);
    if (hstatus == HAL_OK)
      return len;
    else
      return -1;
  }
  return -1;
}

void process_character(char ch) {
	static uint32_t strlen = 0;
	switch (ch) {
	case '\0':
		printf("Received: %s\n\r", rx_buffer);
		rx_buffer[0] = '\0';
		strlen = 0;
		break;
    default:
    	//if statement used to prevent strncat from overflowing rx_buffer
    	if(strlen < BUFFER_SIZE) {
    		strncat((char*)&rx_buffer, &ch, 1);
    	}

	}
}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart) {
	printf("UART Error\n\r");
	Error_Handler();
}

void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t offset) {
	static uint16_t last_offset = 0;

	if (offset != last_offset) {

		if (offset < last_offset) {
			last_offset = 0;
		}

		while (last_offset < offset) {
			process_character((char) DMA_buffer[last_offset]);
			++last_offset;
		}
	}
}

